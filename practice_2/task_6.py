def choose_variant():
    """Спросить у игрока режим игры.

    Returns:
        str: Строка, введённая игроком: '1' — загадать слово самому,
            '2' — угадывать слово из словаря words.
    """
    return input(
        'Приветствую тебя в игре "виселица": '
        "Загадать слово самому(1) "
        "или угадывать слово из словаря(2): "
    )


def choose_word(variant):
    """Выбрать слово и подсказку для выбранного режима.

    Args:
        variant (str): Режим игры. '1' — слово и подсказку вводит
            человек; любое другое значение — случайная категория
            словаря words (она станет подсказкой) и случайное слово
            из этой категории.

    Returns:
        tuple[str, str]: Пара (подсказка, слово).
    """
    if variant == "1":
        clue = input("Введите подсказку: ")
        word = input("Введите слово: ")
    else:
        clue = random.choice(list(words.keys()))
        word = random.choice(words[clue])
    return clue, word


def ask_letter(secret, clue):
    """Запросить у игрока букву.

    Если вместо буквы игрок ввёл слово «подсказка», печатается
    подсказка и буква запрашивается ещё раз.

    Args:
        secret (list[str]): Маска слова, показывается в приглашении.
        clue (str): Подсказка к слову.

    Returns:
        str: Введённая игроком буква.
    """
    letter = input(f'Введите букву "{"".join(secret)}": ')
    if letter.lower() == "подсказка":
        print(f"Подсказка: {clue}")
        letter = input(f'Введите букву "{"".join(secret)}": ')
    return letter


def open_letter(letter, word, secret):
    """Открыть в маске все вхождения буквы в слово.

    Сравнение идёт без учёта регистра; угаданная буква ставится
    в маску на ту же позицию, что и в слове.

    Args:
        letter (str): Буква, введённая игроком.
        word (str): Загаданное слово.
        secret (list[str]): Маска слова, изменяется на месте.

    Returns:
        bool: True, если буква нашлась в слове хотя бы раз.
    """
    flag = False
    for ind, letter_word in enumerate(word):
        if letter.lower() == letter_word.lower():
            secret[ind] = word[ind]
            print(f'Вы угадали: {"".join(secret)}')
            flag = True
    return flag


def play(clue, word):
    """Игровой цикл: работает, пока игрок не выиграет или не проиграет.

    В маске слова каждая неугаданная буква заменена звёздочкой.
    Счётчик ошибок служит индексом текущего рисунка в списке man.
    6 ошибок — нарисован весь человечек, игра проиграна.
    Все звёздочки открыты — слово угадано.

    Args:
        clue (str): Подсказка к слову.
        word (str): Загаданное слово.
    """
    secret = ["*" for _ in range(len(word))]
    lose = 0
    while True:
        letter = ask_letter(secret, clue)
        if not open_letter(letter, word, secret):
            lose += 1
        print(man[lose])
        print(
            f"ОСТАЛОСЬ ПОПЫТОК: {6 - lose} "
            '(если нужна ПОДСКАЗКА вместо буквы введи слово: "ПОДСКАЗКА")'
        )
        if lose == 6:
            print("ВЫ ПРОИГРАЛИ")
            break
        if "".join(secret).lower() == word.lower():
            print("ВЫ ПОБЕДИЛИ!!!!!")
            break


play(*choose_word(choose_variant()))
